## .npr projects. A project is a directory of Nim form units plus a generated
## program file that loads them.

import std/[json, os]

type
  TProject* = ref object
    name*: string
    dir*: string
    mainUnit*: string
    units*: seq[string]

  TProgramForm* = object
    unitName*: string
    typeName*: string

proc nclPath*(): string =
  currentSourcePath().parentDir()

proc projectFile*(p: TProject): string = p.dir / (p.name & ".npr")
proc unitNim*(p: TProject, unitName: string): string = p.dir / (unitName & ".nim")
proc unitNfm*(p: TProject, unitName: string): string = p.dir / (unitName & ".nfm")
proc programFile*(p: TProject): string = p.dir / (p.name & ".nim")
proc outputFile*(p: TProject): string = p.dir / p.name

proc saveProject*(p: TProject) =
  createDir(p.dir)
  let node = %*{
    "name": p.name,
    "main": p.mainUnit,
    "units": p.units
  }
  writeFile(p.projectFile, pretty(node))

proc loadProject*(path: string): TProject =
  let node = parseFile(path)
  result = TProject()
  result.dir = path.parentDir
  result.name = node["name"].getStr
  result.mainUnit = node["main"].getStr
  for u in node["units"]:
    result.units.add(u.getStr)
  if result.mainUnit.len == 0 and result.units.len > 0:
    result.mainUnit = result.units[0]

proc writeNimCfg*(p: TProject) =
  let cfg = "--path:\"" & nclPath() & "\"\n"
  writeFile(p.dir / "nim.cfg", cfg)

proc generateProgram*(forms: seq[TProgramForm], mainUnit: string): string =
  result = "# Generated by Nazarus. Rewritten when the project is saved or run.\n"
  result.add("import os\nimport ncl\n")
  for f in forms:
    result.add("import " & f.unitName & "\n")
  result.add("\n")
  for f in forms:
    result.add("let " & f.unitName & "Form = load" & f.typeName &
      "(getAppDir() / \"" & f.unitName & ".nfm\")\n")
  var main = mainUnit
  if main.len == 0 and forms.len > 0: main = forms[0].unitName
  result.add("application.mainForm = " & main & "Form\n")
  result.add("application.run()\n")

proc writeProgram*(p: TProject, forms: seq[TProgramForm]) =
  writeFile(p.programFile, generateProgram(forms, p.mainUnit))
  writeNimCfg(p)

proc validUnitName*(name: string): bool =
  if name.len == 0 or name[0] notin {'A' .. 'Z', 'a' .. 'z', '_'}: return false
  for ch in name:
    if ch notin {'A' .. 'Z', 'a' .. 'z', '0' .. '9', '_'}: return false
  result = true

proc freshUnitName*(p: TProject): string =
  var i = 1
  while true:
    result = "unit" & $i
    if result notin p.units: return
    inc i

proc projectNameFromPath*(path: string): string =
  result = path.extractFilename.changeFileExt("")
  if result.len == 0: result = "Project1"
  var cleaned = ""
  for ch in result:
    if ch in {'A' .. 'Z', 'a' .. 'z', '0' .. '9', '_'}: cleaned.add(ch)
  if cleaned.len == 0 or cleaned[0] in {'0' .. '9'}: cleaned = "P" & cleaned
  result = cleaned
